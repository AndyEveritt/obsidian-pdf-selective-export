import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFile, mkdir, readFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Install each successful build into the demo vault so it can be tested there.
const { id: pluginId } = JSON.parse(await readFile('manifest.json', 'utf8'));
const demoPluginDir = `demo-vault/.obsidian/plugins/${pluginId}`;
const copyToDemoVault = {
	name: 'copy-to-demo-vault',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			await mkdir(demoPluginDir, { recursive: true });
			for (const file of ['main.js', 'manifest.json', 'styles.css']) {
				await copyFile(file, `${demoPluginDir}/${file}`);
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [copyToDemoVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
